// Checks the published docs (docs/**/*.md) so the examples partners and their AI agents copy stay correct:
//   1. every ```typescript block type-checks against the SDK source,
//   2. every relative link and #anchor resolves,
//   3. every skill has valid frontmatter.
// Run with `bun run docs:check`. Exits 1 on any failure.

import { Glob } from "bun";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const docsDir = join(root, "docs");
const outDir = join(root, ".docs-check");

// Files whose code is not type-checked. The changelog keeps examples of APIs as they were.
const SKIP_FILES = ["CHANGELOG.md"];

// Blocks that are not meant to compile (API listings, signatures), matched by text inside the block.
// Kept here instead of as markers in the docs, which sync to GitBook as-is.
const SKIP_BLOCKS: { file: string; contains: string; reason: string }[] = [
  { file: "1.3_lucraflows.md", contains: "// and one of the below", reason: "Lists every flow method, with optional args" },
];

type Failure = { file: string; line: number; message: string };
const failures: Failure[] = [];

const docFiles = [...new Glob("**/*.md").scanSync(docsDir)].sort().map((f) => join(docsDir, f));
const docs = new Map(docFiles.map((file) => [file, readFileSync(file, "utf8")]));

// ---------------------------------------------------------------------------
// 1. Type-check code blocks
// ---------------------------------------------------------------------------

type Block = { file: string; startLine: number; code: string };

function extractBlocks(file: string, text: string): Block[] {
  const lines = text.split("\n");
  const blocks: Block[] = [];
  for (let i = 0; i < lines.length; i++) {
    const open = lines[i].match(/^```(typescript|ts)\s*$/);
    if (!open) continue;
    const end = lines.findIndex((l, j) => j > i && /^```\s*$/.test(l));
    if (end === -1) {
      failures.push({ file, line: i + 1, message: "Unclosed code block" });
      break;
    }
    const code = lines.slice(i + 1, end).join("\n");
    const skipped = SKIP_BLOCKS.some((s) => relative(docsDir, file) === s.file && code.includes(s.contains));
    if (!skipped) blocks.push({ file, startLine: i + 2, code });
    i = end;
  }
  return blocks;
}

// Snippets further down a page rely on imports shown earlier on it, so every public export of the
// SDK is in scope as a global. Generated from index.ts so it can't drift from the real exports.
function sdkGlobals() {
  const index = readFileSync(join(root, "index.ts"), "utf8");
  const names = (re: RegExp) =>
    [...index.matchAll(re)].flatMap((m) => m[1].split(",").map((n) => n.trim()).filter(Boolean));
  const types = names(/export type \{([^}]*)\}/g);
  const values = names(/export \{([^}]*)\}/g);
  return [
    "// Generated by scripts/check-docs.ts from index.ts.",
    ...types.map((n) => `type ${n} = import("lucra-web-sdk").${n};`),
    // A class or enum is both a value and a type.
    ...values.map((n) => `declare const ${n}: typeof import("lucra-web-sdk").${n};\ntype ${n} = import("lucra-web-sdk").${n};`),
  ].join("\n");
}

function checkTypes() {
  const blocks = [...docs]
    .filter(([file]) => !SKIP_FILES.includes(relative(docsDir, file)))
    .flatMap(([file, text]) => extractBlocks(file, text));
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(join(outDir, "blocks"), { recursive: true });
  writeFileSync(join(outDir, "sdk-globals.d.ts"), sdkGlobals() + "\n");

  const sources = new Map<string, Block>();
  blocks.forEach((block, i) => {
    const name = `blocks/${String(i).padStart(3, "0")}.ts`;
    sources.set(name, block);
    writeFileSync(join(outDir, name), block.code + "\n");
  });
  writeFileSync(
    join(outDir, "tsconfig.json"),
    JSON.stringify(
      {
        compilerOptions: {
          lib: ["ESNext", "DOM"],
          target: "ESNext",
          module: "ESNext",
          moduleResolution: "bundler",
          moduleDetection: "force",
          strict: true,
          noEmit: true,
          skipLibCheck: true,
          paths: { "lucra-web-sdk": ["../index.ts"], "lucra-web-sdk/types": ["../types/types.ts"] },
        },
        files: ["sdk-globals.d.ts", "../scripts/docs-check-globals.d.ts", ...sources.keys()],
      },
      null,
      2,
    ),
  );

  const tsc = Bun.spawnSync(["bunx", "tsc", "--project", join(outDir, "tsconfig.json"), "--pretty", "false"], {
    cwd: root,
  });
  const output = tsc.stdout.toString() + tsc.stderr.toString();
  for (const line of output.split("\n")) {
    const m = line.match(/^(?:\.docs-check\/)?(blocks\/\d+\.ts)\((\d+),\d+\): error (TS\d+: .*)$/);
    if (m) {
      const block = sources.get(m[1])!;
      failures.push({ file: block.file, line: block.startLine + Number(m[2]) - 1, message: m[3] });
    } else if (/error TS\d+/.test(line)) {
      failures.push({ file: join(root, "scripts/docs-check-globals.d.ts"), line: 1, message: line });
    }
  }
  if (tsc.exitCode !== 0 && !failures.length) {
    failures.push({ file: outDir, line: 1, message: `tsc failed:\n${output}` });
  }
  return blocks.length;
}

// ---------------------------------------------------------------------------
// 2. Relative links and anchors
// ---------------------------------------------------------------------------

// GitBook-style heading slugs: lowercase, drop punctuation, spaces to hyphens.
function slug(heading: string) {
  return heading
    .trim()
    .toLowerCase()
    .replace(/`/g, "")
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .replace(/\s/g, "-");
}

function anchorsOf(text: string) {
  const anchors = new Set<string>();
  const counts = new Map<string, number>();
  let inFence = false;
  for (const line of text.split("\n")) {
    if (/^```/.test(line)) inFence = !inFence;
    const m = !inFence && line.match(/^#{1,6}\s+(.+?)\s*#*\s*$/);
    if (!m) continue;
    const base = slug(m[1]);
    const n = counts.get(base) ?? 0;
    counts.set(base, n + 1);
    anchors.add(n ? `${base}-${n}` : base);
  }
  return anchors;
}

function checkLinks() {
  const anchors = new Map([...docs].map(([file, text]) => [file, anchorsOf(text)]));
  let count = 0;
  for (const [file, text] of docs) {
    let inFence = false;
    text.split("\n").forEach((line, i) => {
      if (/^```/.test(line)) inFence = !inFence;
      if (inFence) return;
      for (const m of line.replace(/`[^`]*`/g, "").matchAll(/\]\(([^)\s]+)\)/g)) {
        const href = m[1];
        if (/^[a-z]+:/i.test(href)) continue; // https:, mailto:, ...
        count++;
        const [path, anchor] = href.split("#");
        const target = path ? resolve(dirname(file), path) : file;
        if (!existsSync(target)) {
          failures.push({ file, line: i + 1, message: `Broken link: ${href}` });
        } else if (anchor && anchors.has(target) && !anchors.get(target)!.has(anchor)) {
          failures.push({ file, line: i + 1, message: `Missing anchor #${anchor} in ${relative(root, target)}` });
        }
      }
    });
  }
  return count;
}

// ---------------------------------------------------------------------------
// 3. Skill frontmatter
// ---------------------------------------------------------------------------

function checkSkills() {
  const skills = docFiles.filter((f) => /\/skills\/[^/]+\/SKILL\.md$/.test(f));
  for (const file of skills) {
    const fm = docs.get(file)!.match(/^---\n([\s\S]*?)\n---\n/);
    const folder = file.split("/").at(-2);
    if (!fm) {
      failures.push({ file, line: 1, message: "Missing frontmatter" });
      continue;
    }
    // `[ \t]` not `\s`: an empty key must not borrow the next line's value.
    const name = fm[1].match(/^name:[ \t]*(\S.*)$/m)?.[1].trim();
    if (name !== folder) failures.push({ file, line: 1, message: `name "${name ?? ""}" does not match folder "${folder}"` });
    // Inline value, or a block scalar (`>` / `|`) followed by an indented non-empty line.
    const description = /^description:[ \t]*(?![>|][-+]?[ \t]*$)\S|^description:[ \t]*[>|][-+]?[ \t]*\n[ \t]+\S/m;
    if (!description.test(fm[1])) failures.push({ file, line: 1, message: "Missing description" });
  }
  return skills.length;
}

const blockCount = checkTypes();
const linkCount = checkLinks();
const skillCount = checkSkills();

for (const f of failures) console.error(`${relative(root, f.file)}:${f.line}: ${f.message}`);
console.log(
  `docs:check: ${blockCount} code blocks, ${linkCount} links, ${skillCount} skills: ` +
    (failures.length ? `${failures.length} problem(s)` : "OK"),
);
process.exit(failures.length ? 1 : 0);
