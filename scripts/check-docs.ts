// Checks the published docs (docs/**/*.md) so the examples integrators and their AI agents copy stay correct:
//   1. every typescript block compiles against the SDK (typescript-docs-verifier),
//   2. every relative link and #anchor resolves (remark-validate-links),
//   3. every skill has valid frontmatter.
// Run with `bun run docs:check`. Exits 1 on any failure. Type-checks against dist/, so build first.

import { Glob } from "bun";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const outDir = ".docs-check";

// The changelog keeps examples of APIs as they were, so its code is not type-checked.
// To skip a single block, fence it as `javascript` instead of `typescript` (e.g. API listings).
const typeCheckedDocs = [...new Glob("docs/**/*.md").scanSync(root)].filter((f) => !f.endsWith("CHANGELOG.md")).sort();

function run(label: string, cmd: string[]) {
  console.log(`\n== ${label}`);
  const ok = Bun.spawnSync(cmd, { cwd: root, stdout: "inherit", stderr: "inherit" }).exitCode === 0;
  if (ok) console.log("OK");
  return ok;
}

// Snippets further down a page rely on imports shown earlier on it, so every public export of the
// SDK is in scope as a global, generated from index.ts so it can't drift. The verifier compiles each
// block as the only root file, so the globals reach it as a `types` package, not through `files`.
function writeGlobals() {
  const index = readFileSync(join(root, "index.ts"), "utf8");
  const names = (re: RegExp) =>
    [...index.matchAll(re)].flatMap((m) => m[1].split(",").map((n) => n.trim()).filter(Boolean));
  const sdk = 'import("lucra-web-sdk")';
  const lines = [
    "// Generated by scripts/check-docs.ts from index.ts and scripts/docs-check-globals.d.ts.",
    ...names(/export type \{([^}]*)\}/g).map((n) => `type ${n} = ${sdk}.${n};`),
    // A class or enum is both a value and a type.
    ...names(/export \{([^}]*)\}/g).map((n) => `declare const ${n}: typeof ${sdk}.${n};\ntype ${n} = ${sdk}.${n};`),
    readFileSync(join(root, "scripts/docs-check-globals.d.ts"), "utf8"),
  ];
  mkdirSync(join(root, outDir, "types/lucra-docs"), { recursive: true });
  writeFileSync(join(root, outDir, "types/lucra-docs/index.d.ts"), lines.join("\n"));
  writeFileSync(
    join(root, outDir, "tsconfig.json"),
    JSON.stringify({
      compilerOptions: {
        lib: ["ESNext", "DOM"],
        target: "ESNext",
        module: "ESNext",
        moduleResolution: "bundler",
        moduleDetection: "force", // snippets use top-level await
        strict: true,
        noEmit: true,
        skipLibCheck: true,
        typeRoots: [`./${outDir}/types`], // resolved from the working directory
        types: ["lucra-docs"],
      },
    }),
  );
}

// No library validates Agent Skills frontmatter for production use yet. `claude plugin validate`
// replaces this once the skills are packaged as a plugin (CHA-1017).
function checkSkills() {
  console.log("\n== Skill frontmatter");
  let ok = true;
  for (const file of new Glob("docs/skills/*/SKILL.md").scanSync(root)) {
    // Normalize CRLF so a Windows checkout parses the same as LF.
    const text = readFileSync(join(root, file), "utf8").replace(/\r\n/g, "\n");
    const fm = text.match(/^---\n([\s\S]*?)\n---(?:\n|$)/)?.[1];
    const folder = file.split("/").at(-2);
    const fail = (message: string) => {
      console.error(`${file}:1: ${message}`);
      ok = false;
    };
    if (fm === undefined) {
      fail("Missing frontmatter");
      continue;
    }
    let data: unknown;
    try {
      data = Bun.YAML.parse(fm);
    } catch (e) {
      fail(`Invalid frontmatter YAML: ${e instanceof Error ? e.message : e}`);
      continue;
    }
    const { name, description } = (data && typeof data === "object" ? data : {}) as Record<string, unknown>;
    if (name !== folder) fail(`name "${typeof name === "string" ? name : ""}" does not match folder "${folder}"`);
    if (typeof description !== "string" || !description.trim()) fail("Missing description");
  }
  if (ok) console.log("OK");
  return ok;
}

writeGlobals();
const results = [
  run("Code blocks", [
    "bunx", "typescript-docs-verifier", "--project", `${outDir}/tsconfig.json`, "--input-files", ...typeCheckedDocs,
  ]),
  run("Links and anchors", ["bunx", "remark", "docs", "--use", "remark-validate-links", "--no-stdout", "--quiet", "--frail"]),
  checkSkills(),
];
process.exit(results.every(Boolean) ? 0 : 1);
